package com.eduplay.backend.progress.dto;

import com.eduplay.backend.grade.GradeCatalog;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import java.time.Instant;
import java.util.UUID;

/** One played mini-game, queued on the device until connectivity returns. */
public record GameResultItem(
        @Schema(description = "UUID generated by the Unity client; re-sending the same id is ignored")
        @NotNull UUID id,
        @Schema(description = "Grade the game was played in (ecd_a or ecd_b), not the child's current grade",
                example = "ecd_a")
        @NotNull @Pattern(regexp = GradeCatalog.PATTERN, message = GradeCatalog.MESSAGE) String gradeId,
        @NotNull @Pattern(regexp = ContentIds.PATTERN, message = ContentIds.MESSAGE) String sectionId,
        @NotNull @Pattern(regexp = ContentIds.PATTERN, message = ContentIds.MESSAGE) String topicId,
        @NotNull @Pattern(regexp = ContentIds.PATTERN, message = ContentIds.MESSAGE) String lessonId,
        @NotNull @Min(0) @Max(1000) Integer gameIndex,
        @NotNull @Pattern(regexp = "^[A-Za-z0-9_.-]{1,64}$", message = "must be 1-64 characters") String gameType,
        @Schema(description = "Percent correct, 0-100, for every game type", minimum = "0", maximum = "100")
        @NotNull @Min(0) @Max(100) Integer score,
        @NotNull @Min(0) @Max(10_000) Integer attempts,
        @NotNull @Min(0) @Max(10_000) Integer mistakes,
        @NotNull @Min(0) @Max(86_400) Integer durationSeconds,
        @NotNull Boolean completed,
        @NotNull Instant playedAt) {
}
