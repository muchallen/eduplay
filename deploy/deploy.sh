#!/usr/bin/env bash
# Deploys one release on the EC2 host. Run as root from /opt/eduplay by the CI/CD
# pipeline (or by hand): sudo /opt/eduplay/deploy.sh <registry>/<repo>:<tag> [site-address]
#
# site-address is the public host name, e.g. api.example.com. Caddy then obtains a Let's Encrypt
# certificate and serves the API on both HTTPS (443) and plain HTTP (80), without redirecting.
# Omitted, the current value in .env is kept (":80", plain HTTP only, on a fresh host).
#
# Idempotent. On the first run it creates /opt/eduplay/.env with freshly generated
# secrets; those secrets never leave the host and later runs never overwrite them.
set -euo pipefail

APP_IMAGE="${1:?usage: deploy.sh <image> [site-address]}"
SITE_ADDRESS="${2:-}"
DIR=/opt/eduplay
COMPOSE=(docker compose -f "$DIR/docker-compose.prod.yml" --project-directory "$DIR")
cd "$DIR"

if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
  apt-get update -q
  apt-get install -y -q docker.io docker-compose-v2
fi
systemctl enable --now docker >/dev/null

if [ ! -f .env ]; then
  echo "First deployment: generating $DIR/.env"
  (
    umask 077
    cat > .env <<EOF
# Generated by deploy.sh on $(date -u +%FT%TZ). Edit here, then re-run deploy.sh or
# 'docker compose -f docker-compose.prod.yml up -d' to apply.
SPRING_PROFILES_ACTIVE=prod
FORWARD_HEADERS_STRATEGY=native
SWAGGER_ENABLED=true
CORS_ALLOWED_ORIGINS=
SITE_ADDRESS=:80

DB_NAME=eduplay
DB_USERNAME=eduplay
DB_PASSWORD=$(openssl rand -hex 24)
DB_SSL_MODE=disable
DB_POOL_SIZE=10

JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
JWT_PREVIOUS_SECRETS=

MAIL_ENABLED=false
MAIL_FROM=Eduplay <no-reply@eduplay.example>
SMTP_HOST=localhost
SMTP_PORT=587
APP_PASSWORD_RESET_URL=https://eduplay.example/reset-password
APP_EMAIL_VERIFICATION_URL=https://eduplay.example/verify-email

PRIVACY_POLICY_VERSION=2026-01
APP_MEMORY_LIMIT=1536m
EOF
  )
fi

# Sets KEY=VALUE in .env, replacing an existing line (kept there for manual restarts).
set_env() {
  if grep -q "^$1=" .env; then
    sed -i "s|^$1=.*|$1=$2|" .env
  else
    printf '%s=%s\n' "$1" "$2" >> .env
  fi
}

set_env APP_IMAGE "$APP_IMAGE"
if [ -n "$SITE_ADDRESS" ]; then
  # Listing the http:// address explicitly stops Caddy from redirecting HTTP to HTTPS.
  set_env SITE_ADDRESS "http://$SITE_ADDRESS, https://$SITE_ADDRESS"
fi

"${COMPOSE[@]}" pull --quiet
# --wait blocks until every service is healthy (or fails the deployment after the timeout).
"${COMPOSE[@]}" up -d --remove-orphans --wait --wait-timeout 240

# Registry credentials are only needed for the pull; do not leave them on disk.
docker logout "${APP_IMAGE%%/*}" >/dev/null 2>&1 || true
docker image prune -af --filter "until=168h" >/dev/null 2>&1 || true

echo "Deployed ${APP_IMAGE}"
"${COMPOSE[@]}" ps --format 'table {{.Service}}\t{{.Status}}'
